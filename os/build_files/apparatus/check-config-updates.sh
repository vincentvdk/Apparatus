#!/bin/bash
REPO_URL_FILE="$HOME/.config/apparatus/chezmoi-dotfiles"
DEFAULT_REPO="https://github.com/vincentvdk/apparatus-dotfiles.git"
STATE_DIR="$HOME/.local/state/apparatus"
HASH_FILE="$STATE_DIR/config-update-hash"

# Self-heal: Hyprland >= 0.57 auto-generates a stock hyprland.lua when it is
# missing and then prefers it over hyprland.conf, silently shadowing the
# Apparatus config (this happens on machines upgraded from older images that
# only shipped hyprland.conf). If the user's hyprland.lua is that generated
# example, replace it with the shipped one, or remove it if the image ships none.
HYPR_LUA="$HOME/.config/hypr/hyprland.lua"
if [ -f "$HYPR_LUA" ] && head -n 5 "$HYPR_LUA" | grep -q "AUTOGENERATED HYPRLAND CONFIG"; then
    if [ -f /usr/share/apparatus/hypr/hyprland.lua ]; then
        cp /usr/share/apparatus/hypr/hyprland.lua "$HYPR_LUA"
    else
        rm -f "$HYPR_LUA"
    fi
fi

# Determine repo URL
if [ -f "$REPO_URL_FILE" ]; then
    REPO=$(cat "$REPO_URL_FILE")
    [[ "$REPO" != http* ]] && REPO="https://github.com/$REPO.git"
else
    REPO="$DEFAULT_REPO"
fi

# Get latest remote HEAD hash (lightweight, no fetch/clone)
REMOTE_HASH=$(git ls-remote "$REPO" HEAD 2>/dev/null | cut -f1)
[ -z "$REMOTE_HASH" ] && exit 0

mkdir -p "$STATE_DIR"

# Compare with stored hash (first run just stores, no notification)
if [ -f "$HASH_FILE" ]; then
    LOCAL_HASH=$(cat "$HASH_FILE")
    if [ "$REMOTE_HASH" != "$LOCAL_HASH" ]; then
        notify-send -a "Apparatus" "Config Updates Available" \
            "New configuration updates are available.\nRun butler to apply, then 'butler sync' to update distroboxes." \
            -i dialog-information
    fi
fi

echo "$REMOTE_HASH" > "$HASH_FILE"
